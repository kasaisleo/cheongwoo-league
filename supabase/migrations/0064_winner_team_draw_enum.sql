-- ROLLBACK (필요 시)
-- ============================================================
-- Postgres는 enum 값 삭제를 지원하지 않는다. 되돌리려면 타입을 새로 만들어
-- 컬럼을 옮겨야 하므로 이 migration은 실질적으로 forward-only다.
--
-- 다만 'D'를 쓰는 행이 하나도 없으면 enum에 값이 남아 있어도 어떤 계약도
-- 깨지지 않는다(0064만 적용된 상태와 동일). 기능을 되돌리려면 0065의 함수와
