-- ============================================================
-- 0064: winner_team_type enum에 'D'(무승부) 추가 (Phase 2A-8D-2)
--
-- ------------------------------------------------------------
-- 왜 이 파일 하나로 분리했는가
-- ------------------------------------------------------------
-- Postgres는 ALTER TYPE ... ADD VALUE로 추가한 enum 값을 "같은 트랜잭션 안에서"
-- 사용할 수 없다. 0065는 함수 본문과 CHECK constraint에서 'D'를 직접 쓰므로,
-- enum 추가를 0065와 같은 트랜잭션에 넣으면 다음 오류로 실패한다:
--   unsafe use of new value "D" of enum type winner_team_type
--
-- 그래서 이 파일은
--   · BEGIN/COMMIT으로 감싸지 않는다(암묵적 단일 문장 트랜잭션으로 즉시 커밋)
--   · enum 값 추가 외에 아무 것도 하지 않는다
-- 를 지킨다. 0065는 반드시 이 파일이 커밋된 뒤에 실행해야 한다.
--
-- ------------------------------------------------------------
-- 이 파일만 적용된 상태의 안전성
-- ------------------------------------------------------------
-- enum에 값이 하나 늘어날 뿐 어떤 데이터도 바뀌지 않고, 'D'를 쓰는 코드도
-- 아직 없다(0065가 넣는다). matches.winner_team은 NOT NULL을 유지하며 기존
-- 행은 전부 'A'/'B'다. 따라서 0064만 적용된 상태에서 기존 승패 결과 기능은
-- 완전히 정상 동작한다 — 저장·수정·초기화·조회 모두 영향이 없다.
--
-- IF NOT EXISTS를 붙여 재실행이 no-op이 되게 한다.
--
-- 스키마 컬럼·제약·인덱스 변경 없음. 함수 정의 없음. 테이블 DML 없음.
-- backfill 없음.
-- ============================================================

alter type public.winner_team_type add value if not exists 'D';

comment on type public.winner_team_type is
'경기 결과의 승리 팀. A/B는 승패, D는 무승부(2A-8D — Event 복식 Game의 정확한
5:5에만 사용된다). matches.winner_team은 NOT NULL이며, 5:5 ⇔ D 대응과
무승부의 타이브레이크 금지는 0065의 CHECK constraint가 강제한다.';

